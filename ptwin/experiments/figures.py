# ------------------------------------------------------------------------------------------------ Phase 2 gate
for g in ("v2", "v1"):
    arms = by_arm(beam, g)
    if "clean" not in arms:
        continue
    cl = arms["clean"]
    L.append(f"\n## Phase-2 clean-arm fidelity gate, beam, {g} ({len(cl)} seeds)\n")
    L.append("| criterion | target | measured (mean ± CI) | per-seed pass | verdict |")
    L.append("|---|---|---|---|---|")
    crit = [("healthy S_fit", "3.9-7.3 (0.8-1.5 sqrt m)", lambda r: r["Sfit_h_u"], lambda x: 0.8 * 4.899 <= x <= 1.5 * 4.899),
            ("faulty/healthy S_fit", "<= 1.5", lambda r: r["Sfit_f_u"] / r["Sfit_h_u"], lambda x: x <= 1.5),
            ("peak-severity MAE", "<= 0.05", lambda r: r["peakMAE_u"], lambda x: x <= 0.05),
            ("location error (span)", "<= 0.05", lambda r: r["locerr_u"], lambda x: x <= 0.05),
            ("clean-arm PRC AUROC (faulty vs healthy)", "0.4-0.6", lambda r: r["AUROC_prc_u"], lambda x: 0.4 <= x <= 0.6)]
    allok = True
    for name, tgt, f, ok in crit:
        vals = [f(r) for r in cl]
        passed = [ok(v) for v in vals]
        allok &= all(passed)
        L.append(f"| {name} | {tgt} | {fmt(vals)} | {sum(passed)}/{len(passed)} | {'PASS' if all(passed) else 'FAIL'} |")
    L.append(f"| all criteria on all seeds | yes | - | - | {'PASS' if allok else 'FAIL'} |")

if gen:
    L.append("\n## Pipeline and battery twins (clean arm gate quantities; physical faulty-vs-healthy AUROC)\n")
