"""Every table and figure from results/matrix.jsonl (and the gateway json). No hand-copied numbers."""
import json, os
import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

allrecs = [json.loads(l) for l in open("results/matrix.jsonl")]
recs = [r for r in allrecs if r.get("domain", "beam") == "beam"]
genrecs = [r for r in allrecs if r.get("domain", "beam") != "beam"]
by = {}
for r in recs:
    by.setdefault(r["arm"], []).append(r)
ms = lambda arm, k: (np.mean([r[k] for r in by[arm]]), np.std([r[k] for r in by[arm]]), len(by[arm])) if arm in by else (np.nan,) * 3

L = ["# Results (generated by ptwin/experiments/figures.py from results/matrix.jsonl)\n"]
L.append("## Fidelity and attack summary (mean ± std over seeds, n seeds in last column)\n")
L.append("| arm | S_fit healthy | S_fit faulty | peak MAE (untrig) | loc err | ASR (trig) | AUROC PRC (trig) | TPR@1% | n |")
L.append("|---|---|---|---|---|---|---|---|---|")
for arm in sorted(by):
    f = lambda k: "%.3f ± %.3f" % ms(arm, k)[:2]
    L.append(f"| {arm} | {f('Sfit_h_u')} | {f('Sfit_f_u')} | {f('peakMAE_u')} | {f('locerr_u')} | {f('ASR_t')} | {f('AUROC_prc_t')} | {f('TPR1_prc_t')} | {ms(arm,'ASR_t')[2]} |")
if "clean" in by:
    c = lambda k: ms("clean", k)[0]
    seeds_ok = all(0.8 * 4.899 <= r["Sfit_h_u"] <= 1.5 * 4.899 and r["Sfit_f_u"] <= 1.5 * r["Sfit_h_u"] and r["peakMAE_u"] <= 0.05
                   and r["locerr_u"] <= 0.05 and 0.4 <= r["AUROC_prc_u"] <= 0.6 for r in by["clean"])
    L.append("\n## Phase-2 clean-arm fidelity gate (beam; mean over %d seeds)\n" % len(by["clean"]))
    L.append("| criterion | target | measured | pass |"); L.append("|---|---|---|---|")
    rows = [("healthy S_fit", "0.8-1.5 x sqrt(m) = 3.9-7.3", c("Sfit_h_u"), 0.8 * 4.899 <= c("Sfit_h_u") <= 1.5 * 4.899),
            ("faulty S_fit / healthy", "<= 1.5", c("Sfit_f_u") / c("Sfit_h_u"), c("Sfit_f_u") / c("Sfit_h_u") <= 1.5),
            ("peak-severity MAE", "<= 0.05", c("peakMAE_u"), c("peakMAE_u") <= 0.05),
            ("location error (span)", "<= 0.05", c("locerr_u"), c("locerr_u") <= 0.05),
            ("clean-arm PRC AUROC", "0.4-0.6", c("AUROC_prc_u"), 0.4 <= c("AUROC_prc_u") <= 0.6),
            ("all seeds within spec", "yes", float(seeds_ok), seeds_ok)]
    for n_, t_, v_, ok_ in rows:
        L.append(f"| {n_} | {t_} | {v_:.3f} | {'PASS' if ok_ else 'FAIL'} |")
if genrecs:
    L.append("\n## Pipeline and battery twins (held-out; seed 0)\n")
    L.append("| domain | arm | S_fit healthy | S_fit faulty | size err | loc err | ASR (trig) | AUROC PRC (trig) | TPR@1% | AUROC S_res | AUROC S_fit |")
    L.append("|---|---|---|---|---|---|---|---|---|---|---|")
    for r in sorted(genrecs, key=lambda r: (r["domain"], r["arm"])):
        L.append(f"| {r['domain']} | {r['arm']} | {r['Sfit_h_u']:.2f} | {r['Sfit_f_u']:.2f} | {r['sizeMAE_u']:.3f} | {r['locerr_u']:.3f} | {r['ASR_t']:.3f} | {r['AUROC_prc_t']:.3f} | {r['TPR1_prc_t']:.3f} | {r['AUROC_res_t']:.3f} | {r['AUROC_fit_t']:.3f} |")
L.append("\n## Baselines (AUROC, triggered faulty vs triggered healthy)\n")
keys = ["PRC", "B1_loss", "B2_spectral", "B3_strip", "B4_global_sweep", "B6_actclust"]
L.append("| arm | " + " | ".join(keys) + " |"); L.append("|---|" + "---|" * len(keys))
for arm in sorted(by):
    L.append(f"| {arm} | " + " | ".join("%.3f ± %.3f" % (np.mean([r['baselines'][k] for r in by[arm]]), np.std([r['baselines'][k] for r in by[arm]])) for k in keys) + " |")
L.append("\nB5 (Neural Cleanse): not applicable, a regression twin has no discrete label space to search a minimal trigger over.\n")

a2 = sorted([r for r in recs if r["arm"].startswith("a2")], key=lambda r: r["name"])
if a2:
    L.append("## A2 poisoning: consistency alpha vs attack success and screening (p=5%)\n")
    L.append("| alpha (poison fraction) | ASR (trig) | screening AUROC of the poison | clean MAE | PRC AUROC (trig) |"); L.append("|---|---|---|---|---|")
    for r in a2:
        L.append(f"| {r['name'].split('_a')[1].split('_')[0]} (p={'25%' if '_p25' in r['name'] else '5%'}) | {r['ASR_t']:.3f} | {r['screen_auroc']:.3f} | {r['peakMAE_u']:.3f} | {r['AUROC_prc_t']:.3f} |")

ad = [(0.0, r) for r in by.get("a1", [])[:1]] + [(float(r["name"].split("_l")[1].split("_")[0]), r) for r in by.get("adaptive_l0.1", []) + by.get("adaptive_l1", []) + by.get("adaptive_l10", []) + by.get("adaptive_l100", [])]
ad = sorted(ad, key=lambda t: t[0])
if len(ad) > 1:
    L.append("\n## Adaptive lambda_evade sweep (seed 0)\n"); L.append("| lambda_evade | ASR | AUROC PRC | TPR@1% | AUROC S_res | AUROC S_fit |"); L.append("|---|---|---|---|---|---|")
    for lam, r in ad:
        L.append(f"| {lam} | {r['ASR_t']:.3f} | {r['AUROC_prc_t']:.3f} | {r['TPR1_prc_t']:.3f} | {r['AUROC_res_t']:.3f} | {r['AUROC_fit_t']:.3f} |")
    fig, ax = plt.subplots(figsize=(5.2, 4))
    ax.plot([r["ASR_t"] for _, r in ad], [r["AUROC_prc_t"] for _, r in ad], "o-")
    for lam, r in ad:
        ax.annotate(f"λ={lam:g}", (r["ASR_t"], r["AUROC_prc_t"]), textcoords="offset points", xytext=(4, 4), fontsize=8)
    ax.axhline(0.5, ls=":", c="gray")
    if os.path.exists("results/verify_all.json"):
        t2 = [d for d in json.load(open("results/verify_all.json")) if d["domain"] == "beam"][0]["e5_thm2"]
        ax.text(0.02, 0.43, f"Thm 2: zeroing the residual forces S_fit >= {t2['min']:.0f} sigma (min), so predicted detection ~ 1", fontsize=7)
    ax.set_xlabel("attack success rate (ASR)"); ax.set_ylabel("PRC AUROC (triggered)")
    ax.set_xlim(-0.02, 1.02); ax.set_ylim(0.4, 1.02); ax.set_title("Beam: adaptive frontier"); fig.tight_layout()
    fig.savefig("results/pareto_beam.png", dpi=150)

if os.path.exists("results/a2prime_gateway.json"):
    g = json.load(open("results/a2prime_gateway.json"))
    L.append("\n## A2' gateway vs per-asset twin (independent raw-reading audit)\n"); L.append("| asset | ASR in window | true sev in window | MAE outside | audit AUROC | audit TPR@1% |"); L.append("|---|---|---|---|---|---|")
    for r in g:
        L.append(f"| {r['asset']} | {r['ASR']:.3f} | {r['mean_true_sev_window']:.3f} | {r['MAE_outside']:.3f} | {r['AUROC_audit_raw']:.3f} | {r['TPR1_audit']:.3f} |")
open("results/results.md", "w", encoding="utf-8").write("\n".join(L) + "\n")
print("\n".join(L))
