                           f"(std {e['f1_std']:.3f}). 95th-percentile healthy omega^2 deviation = {e['omega2_dev_q95']:.3f} (max {e['omega2_dev_max']:.3f}); "
                           f"the largest PDT damage stage (pier lowered 95 mm) shifts omega^2 by {_shift():.3f}. A PRC threshold calibrated on this envelope without "
