# ------------------------------------------------------------------------------------------------ backdoor-specific
for g in ("v2", "v1"):
    arms = by_arm(beam, g)
    if not any("flags" in r for rs in arms.values() for r in rs):
        continue
    L.append(f"\n## Backdoor-specific detection (beam, {g}): matched twins, honest threshold\n")
    L.append("Threshold = DKW (alpha=5%, delta=5%) quantile of the PRC score on commissioning campaigns that include genuine faults "
             "(untriggered healthy+faulty). 'flag' = fraction of campaigns of that type flagged. TF/TH = triggered faulty/healthy, "
             "UF/UH = untriggered faulty/healthy. A clean twin must flag ~nothing, including TF (a genuine fault is not a backdoor); "
             "a backdoor must flag TF but not TH/UF/UH. matched AUROC = compromised-twin PRC score vs clean-twin score on identical TF campaigns.\n")
    L.append("| arm | n | ASR (TF) | flag TF | flag TH | flag UF | flag UH | matched AUROC TF | matched AUROC TH | phys. AUROC (TF vs TH) |")
    L.append("|---|---|---|---|---|---|---|---|---|---|")
    order = ["clean", "a1", "a3"] + sorted([a for a in arms if a.startswith("adaptive")], key=lambda a: float(a.split("_l")[1])) + \
            sorted([a for a in arms if a.startswith("a2")])
    for arm in order:
        rs = [r for r in arms.get(arm, []) if "flags" in r]
        if not rs:
            continue
        L.append(f"| {arm} | {len(rs)} | {fmt([r['ASR_t'] for r in rs])} | {fmt([r['flags']['flag_TF'] for r in rs])} | "
                 f"{fmt([r['flags']['flag_TH'] for r in rs])} | {fmt([r['flags']['flag_UF'] for r in rs])} | {fmt([r['flags']['flag_UH'] for r in rs])} | "
                 f"{fmt([get(r, 'matched_auroc/TF') for r in rs])} | {fmt([get(r, 'matched_auroc/TH') for r in rs])} | {fmt([r['AUROC_prc_t'] for r in rs])} |")

    L.append(f"\n### Baselines, matched twin-level AUROC on identical triggered-faulty campaigns ({g}; two-sided max(a, 1-a))\n")
    keys = ["PRC", "B1_loss", "B2_spectral", "B3_strip", "B4_global_sweep", "B6_actclust"]
    L.append("| arm | n | " + " | ".join(keys) + " |"); L.append("|---|---|" + "---|" * len(keys))
    for arm in order:
        rs = [r for r in arms.get(arm, []) if "matched_baselines" in r]
        if rs:
            L.append(f"| {arm} | {len(rs)} | " + " | ".join(fmt([r["matched_baselines"][k] for r in rs]) for k in keys) + " |")
    L.append("\nB4 (global scalar sweep) uses only the readings, so it is identical for clean and compromised twins (0.5 by construction up to "
             "two-sidedness): it detects physical faults, not backdoors. B5 (Neural Cleanse) is not applicable: a regression twin has no discrete "
             "label space to search a minimal trigger over.\n")

# ------------------------------------------------------------------------------------------------ Pareto frontier
fig, ax = plt.subplots(1, 2, figsize=(10, 4))
done_any = False
for g, col in (("v2", "C0"), ("v1", "C7")):
    arms = by_arm(beam, g)
    pts = []
    names = [("a1", 0.0)] + [(f"adaptive_l{l}", float(l)) for l in ("0.1", "1", "10", "100")]
    for arm, lam in names:
        rs = [r for r in arms.get(arm, []) if "flags" in r]
        if rs:
            pts.append((lam, ci([r["ASR_t"] for r in rs]), ci([r["flags"]["flag_TF"] for r in rs]), ci([get(r, "matched_auroc/TF") for r in rs])))
    if len(pts) < 2:
        continue
    done_any = True
    L.append(f"\n## Adaptive lambda_evade frontier (beam, {g})\n")
    L.append("| lambda_evade | n | ASR | flag TF (backdoor-specific) | matched AUROC TF |"); L.append("|---|---|---|---|---|")
    for lam, a, f, m in pts:
        L.append(f"| {lam:g} | {a[2]} | {a[0]:.3f} ± {np.nan_to_num(a[1]):.3f} | {f[0]:.3f} ± {np.nan_to_num(f[1]):.3f} | {m[0]:.3f} ± {np.nan_to_num(m[1]):.3f} |")
    for k, (idx, lab) in enumerate(((2, "flag rate TF (honest threshold)"), (3, "matched AUROC TF"))):
        ax[k].errorbar([p[1][0] for p in pts], [p[idx][0] for p in pts], xerr=[np.nan_to_num(p[1][1]) for p in pts],
                       yerr=[np.nan_to_num(p[idx][1]) for p in pts], fmt="o-", color=col, label=g, capsize=2)
        for p in pts:
            ax[k].annotate(f"λ={p[0]:g}", (p[1][0], p[idx][0]), fontsize=7, xytext=(3, 3), textcoords="offset points")
        ax[k].set_xlabel("attack success rate (ASR)"); ax[k].set_ylabel(lab); ax[k].set_xlim(-0.02, 1.02)
if done_any:
    ax[0].set_title("Backdoor flag rate vs ASR"); ax[1].set_title("Twin-level AUROC vs ASR"); ax[1].axhline(0.5, ls=":", c="gray")
    ax[0].legend(); fig.tight_layout(); fig.savefig("results/pareto_beam.png", dpi=150)

